import Foundation
import SwiftParser
import SwiftSyntax

/// Rewrites what Swift compiles only with an Objective-C runtime, which Linux lacks, into code for
/// IrisObjC's method tables (P1-35), keeping every line of the app on its line number:
///
/// - `#selector(...)`, `Selector("…")` and `NSSelectorFromString(_:)` become
///   `_irisSelector("tapped:")`, which registers the module's methods before its first selector;
///   `#keyPath(T.a.b)` becomes `"a.b"`.
/// - `@objc`, `@objcMembers`, `@nonobjc` and the Interface Builder attributes go. What Objective-C
///   would see is registered by code at the end of each file: methods by selector and properties
///   by getter and setter, which is also how storyboards set outlets and send actions.
/// - `@objc` protocols become class-bound protocols, whose optional requirements an extension
///   implements by sending the selector; `delegate?.method?(x)` calls only an object that has the
///   method, as Objective-C does.
/// - `dynamic` properties of `@objc` classes tell key-value observers when they change, and
///   `NotificationCenter`'s `removeObserver` goes through IrisObjC, which sees observers added
///   with a selector. So do `NSMutableAttributedString`'s `addAttribute` and `addAttributes`,
///   which crash on Linux with values that are objects.
///
/// It reads syntax only. The declarations in all the module's files resolve `#selector(m)` and
/// tell which methods Objective-C would see.
final class ObjCRewriter {
    private let files: [(path: String, tree: SourceFileSyntax)]
    private var types: [String: TypeInfo] = [:]
    /// Types by the last part of their name, `Inner` for `Outer.Inner`.
    private var typesByLastName: [String: [TypeInfo]] = [:]
    private var objcProtocolsOfType: [ObjectIdentifier: [TypeInfo]] = [:]
    /// Optional requirements of `@objc` protocols, by name.
    private var optionalRequirements: [String: [Member]] = [:]
    /// What the rewrite found and did, by kind, for irisrun-ios-build's summary.
    private(set) var counts: [String: Int] = [:]

    /// Files by their path in the module, which names their registration function.
    init(files: [(path: String, source: String)]) {
        self.files = files.map { ($0.path, Parser.parse(source: $0.source)) }
        for (index, file) in self.files.enumerated() {
            Indexer(self, file: index).walk(file.tree)
            if file.tree.hasError { count("files with syntax errors") }
        }
        for type in types.values {
            typesByLastName[String(type.name.split(separator: ".").last ?? ""), default: []].append(type)
        }
        for type in types.values where type.kind == .protocol && type.objcProtocol {
            for member in type.members where member.optional {
                optionalRequirements[member.plainName, default: []].append(member)
            }
        }
    }

    /// The rewritten files, in order, and a file of the module that registers their methods.
    func rewrite() -> (files: [String], registration: String) {
        // Every #selector first: a method gets registered when any file names it.
        let edits = files.indices.map { Editor(self, file: $0).edits() }
        var registering: [String] = []
        let sources = files.indices.map { index in
            var source = applying(edits[index], to: files[index].tree.description)
            if let appendix = appendix(forFile: index) {
                source += (source.isEmpty || source.hasSuffix("\n") ? "" : "\n") + appendix + "\n"
                registering.append(registrationFunction(index))
            }
            return source
        }
        let registration = """
        // Generated by irisrun-ios-build: the methods of this module that selectors reach, registered
        // before its first selector, as Objective-C registers them when the module loads.
        let _irisMethodsRegistered: Void = {
        \(registering.map { "    \($0)()" }.joined(separator: "\n"))
        }()

        func _irisSelector(_ name: String) -> Selector {
            _ = _irisMethodsRegistered
            return Selector(name)
        }

        """
        return (sources, registration)
    }

    fileprivate func count(_ kind: String, _ number: Int = 1) {
        counts[kind, default: 0] += number
    }

    fileprivate func type(_ name: String) -> TypeInfo {
        if let type = types[name] { return type }
        let type = TypeInfo(name: name)
        types[name] = type
        return type
    }

    // MARK: Looking up declarations

    /// The type `name` means in the type `scope`: nested in it or in its outer types, at file
    /// scope, or else the only type whose name ends that way.
    fileprivate func lookUpType(_ name: String, from scope: String?) -> TypeInfo? {
        var outer = scope?.split(separator: ".").map(String.init) ?? []
        while true {
            if let type = types[(outer + [name]).joined(separator: ".")] { return type }
            guard !outer.isEmpty else { break }
            outer.removeLast()
        }
        let candidates = typesByLastName[String(name.split(separator: ".").last ?? "")] ?? []
        return candidates.count == 1 ? candidates[0] : nil
    }

    /// A type, then its superclasses in the module.
    private func hierarchy(of type: TypeInfo) -> [TypeInfo] {
        var chain = [type]
        while chain.count < 64, let name = chain.last!.superclass,
              let superclass = lookUpType(name, from: chain.last!.name), superclass.kind != .protocol,
              !chain.contains(where: { $0 === superclass }) {
            chain.append(superclass)
        }
        return chain
    }

    /// The `@objc` protocols of the module that a class adopts, itself or through its superclasses
    /// and other protocols.
    private func objcProtocols(of type: TypeInfo) -> [TypeInfo] {
        if let found = objcProtocolsOfType[ObjectIdentifier(type)] { return found }
        var found: [TypeInfo] = []
        var names = hierarchy(of: type).flatMap { type in type.inherited.map { (name: $0, scope: type.name) } }
        while let (name, scope) = names.popLast() {
            guard let adopted = lookUpType(name, from: scope), adopted.kind == .protocol,
                  !found.contains(where: { $0 === adopted }) else { continue }
            found.append(adopted)
            names += adopted.inherited.map { ($0, adopted.name) }
        }
        objcProtocolsOfType[ObjectIdentifier(type)] = found.filter(\.objcProtocol)
        return objcProtocolsOfType[ObjectIdentifier(type)]!
    }

    /// The method or property a selector names: in `base` when it is a type of the module, else in
    /// the type the selector is written in and its superclasses, else anywhere in the module.
    fileprivate func member(_ name: String, labels: [String?]?, property: Bool, base: ExprSyntax?, scope: String?) -> Member? {
        let matches = { (member: Member) in
            member.plainName == name && (property ? member.labels == nil
                : member.labels != nil && (labels == nil || member.plainLabels == labels))
        }
        var start = scope.flatMap { lookUpType($0, from: nil) }
        var anywhere = true
        switch base?.trimmedDescription {
        case nil, "self", "Self": break
        case "super": start = start.flatMap { hierarchy(of: $0).dropFirst().first }
        case let text?:
            start = lookUpType(withoutGenericArguments(text), from: scope)
            // A type outside the module: UIKit's, say.
            anywhere = start == nil && text.first?.isLowercase == true
        }
        let candidates = (start.map(hierarchy) ?? []).flatMap { $0.members.filter(matches) }
        if !candidates.isEmpty || !anywhere {
            return candidates.first(where: \.exposed) ?? candidates.first
        }
        let everywhere = types.values.sorted { $0.name < $1.name }.flatMap { $0.members.filter(matches) }
        return everywhere.first(where: \.exposed) ?? everywhere.first
    }

    /// The selector a `#selector(...)` names, after marking its method for registration.
    fileprivate func selector(of expression: MacroExpansionExprSyntax) -> String {
        guard let argument = expression.arguments.first else { return "" }
        let accessor = argument.label?.text
        var named = argument.expression
        // `#selector((m))` and `#selector(m as (Int) -> Void)` name m.
        while true {
            if let sequence = named.as(SequenceExprSyntax.self), let first = sequence.elements.first {
                named = first
            } else if let tuple = named.as(TupleExprSyntax.self), tuple.elements.count == 1 {
                named = tuple.elements.first!.expression
            } else {
                break
            }
        }
        let reference: DeclReferenceExprSyntax
        let base: ExprSyntax?
        if let access = named.as(MemberAccessExprSyntax.self) {
            (reference, base) = (access.declName, access.base)
        } else if let name = named.as(DeclReferenceExprSyntax.self) {
            (reference, base) = (name, nil)
        } else {
            count("left over: #selector of an expression it can't read")
            return named.trimmedDescription
        }
        let name = unescaped(reference.baseName.text)
        let labels = reference.argumentNames.map { $0.arguments.map { label($0.name) } }
        let found = member(name, labels: labels, property: accessor != nil, base: base, scope: enclosingTypeName(of: expression))
        found?.referenced = true
        count(found == nil ? "#selector named by syntax" : "#selector named from declarations")
        let getter = found?.selector ?? labels.map { objcSelector(name, $0) } ?? name
        return accessor == "setter" ? objcSetter(getter) : getter
    }

    /// The optional requirement a call like `delegate?.method?(x)` calls.
    fileprivate func optionalRequirement(_ name: String, labels: [String?], trailingClosures: Int) -> Member? {
        optionalRequirements[name]?.first { requirement in
            guard let required = requirement.plainLabels, required.count == labels.count + trailingClosures else { return false }
            return Array(required.prefix(labels.count)) == labels
        }
    }

    /// Whether a class's member has a dynamic property's `didSet` tell observers about changes:
    /// Objective-C observes `@objc dynamic` properties.
    fileprivate func isObserved(_ property: VariableDeclSyntax) -> Bool {
        guard let owner = owner(of: property), let type = types[qualifiedName(of: owner)], type.kind == .class, type.nameable else {
            return false
        }
        let exposed = !Set(attributeNames(of: property)).isDisjoint(with: exposingAttributes)
        return exposed || hierarchy(of: type).contains(where: \.objcMembers)
    }

    // MARK: Registering methods

    /// What Objective-C would see of a member of a class: what `@objc` and the like mark, what
    /// `#selector` names, members of `@objcMembers` classes and what implements a requirement of
    /// an `@objc` protocol.
    private func isRegistered(_ member: Member, in type: TypeInfo) -> Bool {
        guard !member.isStatic else { return false }
        if member.exposed || member.referenced { return true }
        if type.kind == .class, hierarchy(of: type).contains(where: \.objcMembers) { return true }
        return objcProtocols(of: type).contains { $0.members.contains { $0.plainName == member.plainName && $0.plainLabels == member.plainLabels } }
    }

    private func registrationFunction(_ file: Int) -> String {
        "_irisRegisterMethods_" + c99Identifier(files[file].path)
    }

    /// Code for the end of a file: an extension of each class that registers the methods the file
    /// declares for it, from inside its scope so that private ones are reachable (and isolated
    /// to the main actor with UIKit's classes), a function that calls them, and implementations
    /// of the optional requirements of its `@objc` protocols. Each goes under the `#if` its
    /// declarations are under.
    private func appendix(forFile file: Int) -> String? {
        var extensions: [String] = []
        var calls: [String] = []
        for type in types.values.sorted(by: { $0.name < $1.name }) {
            let members = type.members.filter { $0.file == file }
            guard !members.isEmpty else { continue }
            if type.kind == .protocol {
                let access = type.isPublic ? "public " : ""
                for requirement in members where requirement.optional {
                    if let implementation = defaultImplementation(of: requirement, access: access) {
                        extensions.append(wrapping("extension \(type.name) { \(implementation) }", in: requirement.conditions))
                        count("optional requirements")
                    }
                }
                continue
            }
            guard type.kind == .class || type.kind == .extended else { continue }
            let registered = members.filter { isRegistered($0, in: type) }
            guard !registered.isEmpty else { continue }
            guard type.nameable else {
                count("left over: members of generic, local or nested private classes", registered.count)
                continue
            }
            for (conditions, group) in Dictionary(grouping: registered, by: \.conditions).sorted(by: { $0.key.joined() < $1.key.joined() }) {
                let entries = group.flatMap { entries(for: $0, of: type.name) }
                guard !entries.isEmpty else { continue }
                let function = "_irisMethods_\(c99Identifier(files[file].path))_\(calls.count)"
                extensions.append(wrapping("""
                    extension \(type.name) { static func \(function)() { _IrisMethods.register(\(type.name).self, [
                    \(entries.map { "    \($0)," }.joined(separator: "\n"))
                    ]) } }
                    """, in: conditions))
                calls.append(wrapping("    _irisRegister { \(type.name).\(function)() }", in: conditions))
            }
        }
        guard !extensions.isEmpty else { return nil }
        return (extensions + ["func \(registrationFunction(file))() {"] + calls + ["}"]).joined(separator: "\n")
    }

    /// The table entries of a method, or of a property's getter and setter.
    private func entries(for member: Member, of type: String) -> [String] {
        if let function = member.decl.as(FunctionDeclSyntax.self) {
            let parameters = function.signature.parameterClause.parameters
            guard case .identifier = function.name.tokenKind, function.genericParameterClause == nil,
                  function.signature.effectSpecifiers?.asyncSpecifier == nil,
                  function.signature.effectSpecifiers?.throwsClause == nil,
                  parameters.count <= 3, !parameters.contains(where: { $0.type.trimmedDescription.hasPrefix("inout ") })
            else {
                count("left over: generic, async, throwing or 4+ argument methods")
                return []
            }
            count("methods registered")
            // A reference to a method without arguments could mean another of its name.
            if parameters.isEmpty {
                return ["\(literal(member.selector)): .init { (o: \(type)) in { o.\(member.name)() } }"]
            }
            let name = member.name + "(" + parameters.map { $0.firstName.text + ":" }.joined() + ")"
            return ["\(literal(member.selector)): .init(\(type).\(name))"]
        }
        count("properties registered")
        var entries = ["\(literal(member.selector)): .init { (o: \(type)) in { o.\(member.name) } }"]
        if member.settable {
            entries.append("\(literal(objcSetter(member.selector))): .init { (o: \(type)) in { o.\(member.name) = $0 } }")
        }
        return entries
    }

    /// An optional requirement's implementation for objects that lack it, which sends the selector:
    /// a subclass of the class that adopts the protocol can have the method, and the call sites
    /// call it only when the object has it.
    private func defaultImplementation(of requirement: Member, access: String) -> String? {
        let send = { (selector: String, arguments: String) in
            "_IrisMethods.send(_irisSelector(\(literal(selector))), to: self, with: [\(arguments)])"
        }
        if let function = requirement.decl.as(FunctionDeclSyntax.self) {
            let parameters = function.signature.parameterClause.parameters.enumerated().map { index, parameter in
                "\(parameter.firstName.text) a\(index): \(parameter.type.trimmedDescription)\(parameter.ellipsis?.text ?? "")"
            }
            let arguments = parameters.indices.map { "a\($0)" }.joined(separator: ", ")
            let result = function.signature.returnClause?.type.trimmedDescription
            let body = send(requirement.selector, arguments) + (result.map { " as! \($0)" } ?? "")
            return "\(access)func \(requirement.name)(\(parameters.joined(separator: ", ")))\(result.map { " -> \($0)" } ?? "") { \(body) }"
        }
        guard let type = requirement.binding?.typeAnnotation?.type.trimmedDescription else { return nil }
        let getter = "get { \(send(requirement.selector, "")) as! \(type) }"
        let setter = requirement.settable ? " set { \(send(objcSetter(requirement.selector), "newValue")) }" : ""
        return "\(access)var \(requirement.name): \(type) { \(getter)\(setter) }"
    }
}

// MARK: - What the module declares

/// A class, struct, enum or protocol of the module, or a type it extends, with what its
/// declaration and extensions declare.
private final class TypeInfo {
    enum Kind { case `class`, `protocol`, other, extended }

    let name: String
    var kind = Kind.extended
    /// Whether code at file scope can name it: not generic, not local, not private inside a type.
    var nameable = true
    var superclass: String?
    /// Types in its inheritance clauses, its declaration's and its extensions'.
    var inherited: [String] = []
    var objcMembers = false
    var objcProtocol = false
    var isPublic = false
    var members: [Member] = []

    init(name: String) {
        self.name = name
    }
}

/// A method or property, as Objective-C would see it.
private final class Member {
    let decl: DeclSyntax
    /// A property's binding.
    let binding: PatternBindingSyntax?
    /// As written, with any backticks.
    let name: String
    /// A method's argument labels; nil for a property.
    let labels: [String?]?
    /// A property's getter.
    let selector: String
    /// Marked `@objc`, `@IBAction`, `@IBOutlet` and the like, or in an `@objc` extension.
    let exposed: Bool
    let isStatic: Bool
    /// An optional requirement of a protocol.
    let optional: Bool
    let settable: Bool
    let file: Int
    /// The `#if` clauses it is under.
    let conditions: [String]
    /// Named by a `#selector`.
    var referenced = false

    var plainName: String {
        unescaped(name)
    }

    var plainLabels: [String?]? {
        labels.map { $0.map { $0.map(unescaped) } }
    }

    init(_ decl: DeclSyntax, binding: PatternBindingSyntax? = nil, name: String, labels: [String?]?, owner: DeclSyntax, file: Int) {
        self.decl = decl
        self.binding = binding
        self.name = name
        self.labels = labels
        self.file = file
        let attributes = attributeNames(of: decl)
        let modifiers = modifierNames(of: decl)
        exposed = !Set(attributes).isDisjoint(with: exposingAttributes)
            || owner.is(ExtensionDeclSyntax.self) && attributeNames(of: owner).contains("objc")
        isStatic = modifiers.contains("static") || modifiers.contains("class")
        optional = modifiers.contains("optional")
        let plainName = unescaped(name)
        selector = objcName(in: decl) ?? labels.map { objcSelector(plainName, $0.map { $0.map(unescaped) }) } ?? plainName
        switch binding?.accessorBlock?.accessors {
        case nil: settable = decl.as(VariableDeclSyntax.self)?.bindingSpecifier.text == "var"
        case .getter: settable = false
        case let .accessors(accessors): settable = accessors.contains { ["set", "willSet", "didSet"].contains($0.accessorSpecifier.text) }
        }
        conditions = ifConditions(of: decl)
    }
}

/// Records the module's types and members.
private final class Indexer: SyntaxVisitor {
    private let rewriter: ObjCRewriter
    private let file: Int

    init(_ rewriter: ObjCRewriter, file: Int) {
        self.rewriter = rewriter
        self.file = file
        super.init(viewMode: .sourceAccurate)
    }

    override func visit(_ node: ClassDeclSyntax) -> SyntaxVisitorContinueKind {
        declare(DeclSyntax(node), as: .class)
    }

    override func visit(_ node: ProtocolDeclSyntax) -> SyntaxVisitorContinueKind {
        declare(DeclSyntax(node), as: .protocol)
    }

    override func visit(_ node: StructDeclSyntax) -> SyntaxVisitorContinueKind {
        declare(DeclSyntax(node), as: .other)
    }

    override func visit(_ node: EnumDeclSyntax) -> SyntaxVisitorContinueKind {
        declare(DeclSyntax(node), as: .other)
    }

    override func visit(_ node: ActorDeclSyntax) -> SyntaxVisitorContinueKind {
        declare(DeclSyntax(node), as: .other)
    }

    override func visit(_ node: ExtensionDeclSyntax) -> SyntaxVisitorContinueKind {
        declare(DeclSyntax(node), as: nil)
    }

    private func declare(_ decl: DeclSyntax, as kind: TypeInfo.Kind?) -> SyntaxVisitorContinueKind {
        let type = rewriter.type(qualifiedName(of: decl))
        let inherited = decl.asProtocol(DeclGroupSyntax.self)?.inheritanceClause?.inheritedTypes.map { typeName($0.type) } ?? []
        if let kind {
            type.kind = kind
            if kind == .class { type.superclass = inherited.first }
        }
        type.nameable = type.nameable && isNameable(decl)
        type.inherited += inherited
        let attributes = attributeNames(of: decl)
        type.objcMembers = type.objcMembers || attributes.contains("objcMembers")
        if kind == .protocol {
            type.objcProtocol = attributes.contains("objc")
            type.isPublic = modifierNames(of: decl).contains { $0 == "public" || $0 == "open" }
        }
        return .visitChildren
    }

    override func visit(_ node: FunctionDeclSyntax) -> SyntaxVisitorContinueKind {
        if let owner = owner(of: node) {
            let labels = node.signature.parameterClause.parameters.map { label($0.firstName) }
            rewriter.type(qualifiedName(of: owner)).members.append(
                Member(DeclSyntax(node), name: node.name.text, labels: labels, owner: owner, file: file)
            )
        }
        return .skipChildren
    }

    override func visit(_ node: VariableDeclSyntax) -> SyntaxVisitorContinueKind {
        if let owner = owner(of: node) {
            for binding in node.bindings {
                guard let name = binding.pattern.as(IdentifierPatternSyntax.self)?.identifier.text else { continue }
                rewriter.type(qualifiedName(of: owner)).members.append(
                    Member(DeclSyntax(node), binding: binding, name: name, labels: nil, owner: owner, file: file)
                )
            }
        }
        return .skipChildren
    }

    override func visit(_ node: InitializerDeclSyntax) -> SyntaxVisitorContinueKind {
        .skipChildren
    }

    override func visit(_ node: SubscriptDeclSyntax) -> SyntaxVisitorContinueKind {
        .skipChildren
    }
}

// MARK: - Rewriting

/// What one file changes: text replaced in place, line breaks kept.
private final class Editor: SyntaxVisitor {
    private let rewriter: ObjCRewriter
    private let file: Int
    private var changes: [(range: Range<Int>, text: String)] = []

    init(_ rewriter: ObjCRewriter, file: Int) {
        self.rewriter = rewriter
        self.file = file
        super.init(viewMode: .sourceAccurate)
    }

    func edits() -> [(range: Range<Int>, text: String)] {
        walk(rewriter.tree(file))
        return changes
    }

    private func replace(_ node: some SyntaxProtocol, with text: String) {
        changes.append((node.positionAfterSkippingLeadingTrivia.utf8Offset ..< node.endPositionBeforeTrailingTrivia.utf8Offset, text))
    }

    private func insert(_ text: String, at position: AbsolutePosition) {
        changes.append((position.utf8Offset ..< position.utf8Offset, text))
    }

    override func visit(_ node: AttributeSyntax) -> SyntaxVisitorContinueKind {
        let name = node.attributeName.trimmedDescription
        if objcAttributes.contains(name) {
            replace(node, with: "")
            rewriter.count("@\(name) removed")
        } else if name == "NSManaged" {
            rewriter.count("left over: @NSManaged")
        }
        return .skipChildren
    }

    override func visit(_ node: ProtocolDeclSyntax) -> SyntaxVisitorContinueKind {
        guard attributeNames(of: node).contains("objc") else { return .visitChildren }
        // Objective-C protocols are for classes, so `weak var delegate: P?` works.
        if let inherited = node.inheritanceClause?.inheritedTypes {
            if !inherited.contains(where: { ["AnyObject", "class"].contains($0.type.trimmedDescription) }), let last = inherited.last {
                insert(", AnyObject", at: last.type.endPositionBeforeTrailingTrivia)
            }
        } else {
            insert(": AnyObject", at: node.name.endPositionBeforeTrailingTrivia)
        }
        rewriter.count("@objc protocols")
        return .visitChildren
    }

    override func visit(_ node: DeclModifierSyntax) -> SyntaxVisitorContinueKind {
        if node.name.text == "optional", let decl = node.parent?.parent, owner(of: decl)?.is(ProtocolDeclSyntax.self) == true {
            replace(node, with: "")
        }
        return .skipChildren
    }

    override func visit(_ node: MacroExpansionExprSyntax) -> SyntaxVisitorContinueKind {
        switch node.macroName.text {
        case "selector":
            replace(node, with: "_irisSelector(\(literal(rewriter.selector(of: node))))")
            return .skipChildren
        case "keyPath":
            // `#keyPath(UIView.layer.cornerRadius)` is "layer.cornerRadius": type names go.
            var keys = (node.arguments.first?.expression.trimmedDescription ?? "").filter { !$0.isWhitespace }.split(separator: ".")
            while keys.count > 1, keys[0].first?.isUppercase == true {
                keys.removeFirst()
            }
            replace(node, with: literal(keys.joined(separator: ".")))
            rewriter.count("#keyPath")
            return .skipChildren
        default:
            return .visitChildren
        }
    }

    override func visit(_ node: FunctionCallExprSyntax) -> SyntaxVisitorContinueKind {
        let labels = node.arguments.map { $0.label.map { unescaped($0.text) } }
        let callee = node.calledExpression
        if let name = callee.as(DeclReferenceExprSyntax.self), ["Selector", "NSSelectorFromString"].contains(name.baseName.text),
           labels == [nil] {
            replace(name, with: "_irisSelector")
            rewriter.count("Selector(_:) and NSSelectorFromString")
        } else if let access = callee.as(MemberAccessExprSyntax.self), let base = access.base {
            switch access.declName.baseName.text {
            // NotificationCenter's, by its receiver and labels: KVO's has forKeyPath:, and apps
            // have removeObserver(_:) methods of their own.
            case "removeObserver" where base.trimmedDescription.lowercased().contains("center")
                && (labels == [nil] || labels == [nil, "name", "object"]):
                replace(access.declName.baseName, with: "_irisRemoveObserver")
                rewriter.count("removeObserver")
            // Foundation on Linux stops the app merging attributes whose values are objects;
            // IrisObjC merges them itself.
            case "addAttribute" where labels == [nil, "value", "range"], "addAttributes" where labels == [nil, "range"]:
                let name = access.declName.baseName.text
                replace(access.declName.baseName, with: "_irisA" + name.dropFirst())
                rewriter.count("addAttribute and addAttributes")
            case "addObserver" where labels.contains("forKeyPath"):
                rewriter.count("left over: addObserver(_:forKeyPath:options:context:)")
            default:
                break
            }
        }
        callingOptionalRequirement(node, labels: labels)
        return .visitChildren
    }

    /// `delegate?.method?(x)` becomes `_irisOptional(delegate, …)?.method(x)`, and
    /// `delegate.method!(x)` `delegate.method(x)`, whose default implementation stops the app
    /// when the object has no such method.
    private func callingOptionalRequirement(_ node: FunctionCallExprSyntax, labels: [String?]) {
        let callee = node.calledExpression
        let chained = callee.as(OptionalChainingExprSyntax.self)
        let forced = callee.as(ForceUnwrapExprSyntax.self)
        guard let access = (chained?.expression ?? forced?.expression)?.as(MemberAccessExprSyntax.self), let base = access.base,
              let requirement = rewriter.optionalRequirement(
                  unescaped(access.declName.baseName.text), labels: labels,
                  trailingClosures: (node.trailingClosure == nil ? 0 : 1) + node.additionalTrailingClosures.count
              )
        else { return }
        rewriter.count("optional requirement calls")
        if let forced {
            replace(forced.exclamationMark, with: "")
            return
        }
        replace(chained!.questionMark, with: "")
        let check = ", _irisSelector(\(literal(requirement.selector))))?"
        insert("_irisOptional(", at: base.positionAfterSkippingLeadingTrivia)
        if let optionalBase = base.as(OptionalChainingExprSyntax.self) {
            replace(optionalBase.questionMark, with: check)
        } else {
            insert(check, at: base.endPositionBeforeTrailingTrivia)
        }
    }

    override func visit(_ node: FunctionDeclSyntax) -> SyntaxVisitorContinueKind {
        if node.name.text == "observeValue", modifierNames(of: node).contains("override") {
            rewriter.count("left over: observeValue(forKeyPath:of:change:context:)")
        }
        return .visitChildren
    }

    /// A `dynamic` property of an `@objc` class tells key-value observers when it changes.
    override func visit(_ node: VariableDeclSyntax) -> SyntaxVisitorContinueKind {
        let modifiers = modifierNames(of: node)
        guard modifiers.contains("dynamic"), node.bindingSpecifier.text == "var", node.bindings.count == 1,
              !modifiers.contains("static"), !modifiers.contains("class"), !modifiers.contains("lazy"),
              let binding = node.bindings.first, let name = binding.pattern.as(IdentifierPatternSyntax.self)?.identifier.text,
              rewriter.isObserved(node), let owner = owner(of: node)
        else { return .visitChildren }
        let notify = { (oldValue: String) in "_irisDidChangeValue(self, \\\(qualifiedName(of: owner)).\(name), from: \(oldValue))" }
        switch binding.accessorBlock?.accessors {
        case nil:
            insert(" { didSet { \(notify("oldValue")) } }", at: binding.endPositionBeforeTrailingTrivia)
        case let .accessors(accessors) where accessors.allSatisfy({ ["willSet", "didSet"].contains($0.accessorSpecifier.text) }):
            if let didSet = accessors.first(where: { $0.accessorSpecifier.text == "didSet" }), let body = didSet.body {
                insert(" \(notify(didSet.parameters?.name.text ?? "oldValue"));", at: body.leftBrace.endPositionBeforeTrailingTrivia)
            } else if let block = binding.accessorBlock {
                insert(" didSet { \(notify("oldValue")) }", at: block.rightBrace.positionAfterSkippingLeadingTrivia)
            }
        default:
            rewriter.count("left over: computed dynamic properties")
            return .visitChildren
        }
        rewriter.count("observable properties")
        return .visitChildren
    }
}

extension ObjCRewriter {
    fileprivate func tree(_ file: Int) -> SourceFileSyntax {
        files[file].tree
    }
}

/// Applies edits to a source's UTF-8 bytes. A replaced line break goes after the replacement, so
/// every line stays on its number.
private func applying(_ edits: [(range: Range<Int>, text: String)], to source: String) -> String {
    var bytes = Array(source.utf8)
    // From the end, and at one place a replacement before an insertion, which comes out in front.
    for edit in edits.sorted(by: { ($0.range.lowerBound, $0.range.isEmpty ? 0 : 1) > ($1.range.lowerBound, $1.range.isEmpty ? 0 : 1) }) {
        let lineBreaks = bytes[edit.range].count { $0 == UInt8(ascii: "\n") }
        bytes.replaceSubrange(edit.range, with: Array((edit.text + String(repeating: "\n", count: lineBreaks)).utf8))
    }
    return String(decoding: bytes, as: UTF8.self)
}

// MARK: - Objective-C names

/// Attributes that mean something only to Objective-C or Interface Builder. Linux rejects `@objc`,
/// `@objcMembers` and `@IBOutlet` of a class type; the others go with them.
private let objcAttributes: Set<String> = [
    "objc", "objcMembers", "nonobjc", "IBAction", "IBOutlet", "IBInspectable", "IBDesignable", "IBSegueAction", "GKInspectable",
]

/// Attributes that show a member to Objective-C.
private let exposingAttributes: Set<String> = ["objc", "IBAction", "IBOutlet", "IBInspectable", "IBSegueAction", "GKInspectable"]

/// English prepositions, after which Swift adds no "With" to a selector (swift/Basic/PartsOfSpeech.def).
private let prepositions: Set<String> = [
    "above", "after", "along", "alongside", "as", "at", "before", "below", "by", "following", "for", "from", "given", "in",
    "including", "inside", "into", "matching", "of", "on", "passing", "preceding", "since", "to", "until", "using", "via",
    "when", "with", "within",
]

/// The selector Swift gives a method, as the compiler names `@objc` methods: `tapped()` → `tapped`,
/// `tapped(_:)` → `tapped:`, `tapped(sender:)` → `tappedWithSender:`, `do(with:and:)` →
/// `doWith:and:`, `init(name:)` → `initWithName:`.
func objcSelector(_ name: String, _ labels: [String?]) -> String {
    guard let first = labels.first else { return name }
    var selector = name
    if let first {
        let firstWord = first.prefix { !$0.isUppercase }.lowercased()
        let lastWord = name[(name.lastIndex(where: \.isUppercase) ?? name.startIndex)...].lowercased()
        if !prepositions.contains(firstWord), !prepositions.contains(lastWord) {
            selector += "With"
        }
        selector += first.prefix(1).uppercased() + first.dropFirst()
    }
    return selector + ":" + labels.dropFirst().map { ($0 ?? "") + ":" }.joined()
}

/// A property's setter: `setTitle:` for `title`.
func objcSetter(_ getter: String) -> String {
    "set" + getter.prefix(1).uppercased() + getter.dropFirst() + ":"
}

/// The name in `@objc(name:)`.
private func objcName(in decl: DeclSyntax) -> String? {
    for attribute in attributes(of: decl) where attribute.attributeName.trimmedDescription == "objc" {
        if case let .objCName(pieces) = attribute.arguments {
            return pieces.map { ($0.name?.text ?? "") + ($0.colon == nil ? "" : ":") }.joined()
        }
    }
    return nil
}

// MARK: - Syntax helpers

private func attributes(of node: some SyntaxProtocol) -> [AttributeSyntax] {
    Syntax(node).asProtocol(WithAttributesSyntax.self)?.attributes.compactMap { $0.as(AttributeSyntax.self) } ?? []
}

private func attributeNames(of node: some SyntaxProtocol) -> [String] {
    attributes(of: node).map { $0.attributeName.trimmedDescription }
}

private func modifierNames(of node: some SyntaxProtocol) -> [String] {
    Syntax(node).asProtocol(WithModifiersSyntax.self)?.modifiers.map(\.name.text) ?? []
}

/// An argument label as written, nil for `_`.
private func label(_ token: TokenSyntax) -> String? {
    token.tokenKind == .wildcard ? nil : token.text
}

private func unescaped(_ name: String) -> String {
    name.hasPrefix("`") ? String(name.dropFirst().dropLast()) : name
}

private func withoutGenericArguments(_ name: String) -> String {
    var depth = 0
    return name.filter { character in
        if character == "<" { depth += 1 } else if character == ">" { depth -= 1 } else { return depth == 0 && !character.isWhitespace }
        return false
    }
}

/// A type's name without generic arguments or attributes: `Outer.Inner` for `Outer.Inner<Int>`.
private func typeName(_ type: TypeSyntax) -> String {
    if let identifier = type.as(IdentifierTypeSyntax.self) { return identifier.name.text }
    if let member = type.as(MemberTypeSyntax.self) { return typeName(member.baseType) + "." + member.name.text }
    if let attributed = type.as(AttributedTypeSyntax.self) { return typeName(attributed.baseType) }
    return type.trimmedDescription
}

/// The type or extension a declaration is a member of; nil at file scope and inside code.
private func owner(of node: some SyntaxProtocol) -> DeclSyntax? {
    var current = node.parent
    while let node = current {
        if node.is(CodeBlockSyntax.self) || node.is(ClosureExprSyntax.self) || node.is(AccessorBlockSyntax.self) { return nil }
        if node.is(MemberBlockSyntax.self) { return node.parent?.as(DeclSyntax.self) }
        current = node.parent
    }
    return nil
}

/// A type's name from file scope, `Outer.Inner`, or the type an extension extends.
private func qualifiedName(of decl: DeclSyntax) -> String {
    let name = decl.as(ExtensionDeclSyntax.self).map { typeName($0.extendedType) } ?? decl.asProtocol(NamedDeclSyntax.self)?.name.text ?? ""
    return owner(of: decl).map { qualifiedName(of: $0) + "." + name } ?? name
}

/// The type or extension that code is written in.
private func enclosingTypeName(of node: some SyntaxProtocol) -> String? {
    sequence(first: Syntax(node), next: \.parent).first { $0.asProtocol(DeclGroupSyntax.self) != nil }
        .flatMap { $0.as(DeclSyntax.self) }.map(qualifiedName)
}

/// Whether code at file scope can name a type: it is not generic, inside a generic type or a
/// function, or private inside another type.
private func isNameable(_ decl: DeclSyntax) -> Bool {
    if decl.asProtocol(WithGenericParametersSyntax.self)?.genericParameterClause != nil
        || decl.as(ExtensionDeclSyntax.self)?.genericWhereClause != nil {
        return false
    }
    if let outer = owner(of: decl) {
        return !modifierNames(of: decl).contains("private") && isNameable(outer)
    }
    return !sequence(first: Syntax(decl), next: \.parent).contains { $0.is(CodeBlockSyntax.self) || $0.is(ClosureExprSyntax.self) }
}

/// The `#if` clauses a node is in, outermost first, each as the directives that pick it:
/// `#if A` / `#elseif B` for the second clause.
private func ifConditions(of node: some SyntaxProtocol) -> [String] {
    sequence(first: Syntax(node), next: \.parent).compactMap { ancestor -> String? in
        guard let clause = ancestor.as(IfConfigClauseSyntax.self), let clauses = clause.parent?.as(IfConfigClauseListSyntax.self) else {
            return nil
        }
        let picked = clauses.prefix { $0.id != clause.id } + [clause]
        return picked.map { $0.poundKeyword.text + ($0.condition.map { " " + $0.trimmedDescription } ?? "") }.joined(separator: "\n")
    }.reversed()
}

/// Code under the `#if` clauses that a declaration is under.
private func wrapping(_ code: String, in conditions: [String]) -> String {
    (conditions + [code] + conditions.map { _ in "#endif" }).joined(separator: "\n")
}
