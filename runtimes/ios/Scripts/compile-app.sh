#!/usr/bin/env bash
# Compiles one SwiftUI app directory, unchanged, against OpenKit (the patched OpenSwiftUI
# checkout). It collects the app's Swift files without tests, strips #Preview blocks, writes a
# SwiftPM package to $IRISRUN_IOS_WORK/apps/<name> that aliases SwiftUI to OpenSwiftUI and
# Observation to OpenObservation, and builds it. On success it prints the executable's path,
# or the module's name when the app has no entry point.
#
#   Scripts/compile-app.sh <app-dir> [swift build options...]
#
# Needs Swift 6.4.1 and Scripts/fetch-openswiftui.sh, and to link an app, the render core that
# OpenSwiftUI draws with: `cargo build -p irisrun-render --release` in the repo. All apps share
# one build directory per configuration, so OpenSwiftUI is compiled once. This is the compile
# step that tools/ios-corpus calls per app.
set -euo pipefail

ios="$(cd "$(dirname "$0")/.." && pwd)"
source "$ios/Scripts/env.sh"
app="$(cd "$1" && pwd)"
shift
name="$(basename "$app" | tr -c 'A-Za-z0-9_\n' '_')"
[[ "$name" =~ ^[A-Za-z_] ]] || name="App_$name"
pkg="$IRISRUN_IOS_WORK/apps/$name"
src="$pkg/Sources/$name"
render_lib="${CARGO_TARGET_DIR:-$ios/../../target}/release"

rm -rf -- "$pkg/Sources"
mkdir -p "$src"
find "$app" -name '*.swift' -not -name Package.swift \
    -not -path '*/.*' -not -path '*Tests/*' -not -path '*/Pods/*' -not -path '*/Carthage/*' \
    -print0 |
    while IFS= read -r -d '' file; do
        out="$src/${file#"$app"/}"
        mkdir -p "$(dirname "$out")"
        python3 "$ios/Scripts/strip-previews.py" < "$file" > "$out"
    done

# An app with an entry point links into an executable; anything else stops at the module.
kind=target
if [ -n "$(find "$src" -name main.swift)" ] || grep -rqE '^[[:space:]]*@main\b' "$src"; then
    kind=executableTarget
    if [ ! -f "$render_lib/libirisrun_render.a" ]; then
        echo "error: no $render_lib/libirisrun_render.a; run: cargo build -p irisrun-render --release" >&2
        exit 1
    fi
fi
cat > "$pkg/Package.swift" <<EOF
// swift-tools-version: 6.0
// Generated by runtimes/ios/Scripts/compile-app.sh from $app
import PackageDescription

let package = Package(
    name: "$name",
    dependencies: [.package(path: "$IRISRUN_IOS_WORK/checkouts/OpenSwiftUI")],
    targets: [
        .$kind(
            name: "$name",
            dependencies: [.product(name: "OpenSwiftUI", package: "OpenSwiftUI")],
            swiftSettings: [
                .unsafeFlags([
                    "-module-alias", "SwiftUI=OpenSwiftUI",
                    "-module-alias", "Observation=OpenObservation",
                ]),
            ],
            linkerSettings: [.unsafeFlags(["-L$render_lib"])]
        ),
    ],
    swiftLanguageModes: [.v5]
)
EOF

# Switching between debug and release in one build directory rebuilds the macro tools and then
# everything that uses them, so each configuration gets its own directory.
config=debug
case " $* " in *" release "* | *"=release "*) config=release ;; esac
build=(swift build --package-path "$pkg" --scratch-path "$IRISRUN_IOS_WORK/build/apps-$config" -j 6 "$@")
"${build[@]}" >&2
if [ "$kind" = executableTarget ]; then
    echo "$("${build[@]}" --show-bin-path)/$name"
else
    echo "$name"
fi
